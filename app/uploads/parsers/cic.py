"""Read the credit score and debt position out of a CIC credit-report PDF.

WHAT THE FILE IS
The report the National Credit Information Centre (Trung tâm Thông tin Tín
dụng Quốc gia, cic.gov.vn) issues on request, as a PDF generated by its
report server (JasperReports). The SME downloads it from the CIC portal or app
and uploads it on step 4. Two kinds exist:

  * "THÔNG TIN TÍN DỤNG KHÁCH HÀNG VAY CÁ NHÂN" — an INDIVIDUAL's report. For a
    small company this is usually the owner's. It carries a score on CIC's
    individual model (bands 403-706 on the reference report) and a rank 1-10.
  * "... KHÁCH HÀNG VAY DOANH NGHIỆP" — a BUSINESS report. Recognised, but no
    sample has been seen yet: the same labels are tried, and whatever cannot be
    read is a warning, not a refusal (a real report must never be bounced
    because our parser is behind).

WHAT IT PRODUCES
  score, rank, scored_on      section II ("Điểm tín dụng", "Hạng", "Ngày chấm
                              điểm"). The rank is cross-checked against the
                              band table printed beside it.
  percentile                  "cao hơn điểm tín dụng của NN% ..."
  debt                        section 2.1, in MILLION đồng (and USD) as CIC
                              prints it: current total, standard (group 1),
                              needs-attention (group 2), bad (groups 3-5).
  negative_history            section 2.2: attention debt in the last 12
                              months or bad debt in the last 5 years.

⚠️ EVIDENCE WEIGHT
The PDF carries no digital signature (checked: no /ByteRange, no signature
dictionary), so it can be edited like any PDF. `signed` records that. Handbook
§5.7 treats external lookups as corroboration; until CIC is queried directly,
this score is self-supplied evidence and underwriting should treat it so.

PERSONAL DATA
The report prints the subject's date of birth, ID-card number, phone and
address. None of it is kept: only the name (to compare with the applicant) is.
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from datetime import date, datetime
from io import BytesIO
from typing import Any

from pypdf import PdfReader
from pypdf.errors import PdfReadError

PARSER_VERSION = "cic-pdf-1.0"
MAX_PAGES = 30
# CIC rescores monthly ("cập nhật định kỳ hàng tháng"), so a report older than
# about a month may no longer show the current score. PROVISIONAL: no policy
# sets this threshold yet; it only raises a warning.
STALE_AFTER_DAYS = 31

# The five labels CIC prints over its ten bands, best first: ranks 1-2 are
# "Rất tốt", 3-4 "Tốt", and so on.
RANK_LABELS = ("very_good", "good", "average", "below_average", "poor")


class CicParseError(ValueError):
    def __init__(self, message: str, code: str) -> None:
        super().__init__(message)
        self.code = code


@dataclass
class CicReport:
    subject_type: str  # "individual" | "business"
    subject_name: str | None
    report_number: str | None
    queried_on: str | None  # ISO date
    signed: bool
    score: int | None
    rank: int | None
    rank_band: list[int] | None  # [low, high] of the band the rank names
    rank_label: str | None
    scored_on: str | None
    percentile: int | None
    lenders: int
    debt_total_vnd_million: float | None
    debt_total_usd: float | None
    debt_standard_vnd_million: float | None
    debt_attention_vnd_million: float | None
    debt_bad_vnd_million: float | None
    negative_history: bool | None
    collateral: str | None
    parser_version: str = PARSER_VERSION
    warnings: list[dict[str, str]] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)

    def age_days(self, today: date) -> int | None:
        ref = self.scored_on or self.queried_on
        return (today - date.fromisoformat(ref)).days if ref else None


def _text(raw: bytes) -> str:
    try:
        reader = PdfReader(BytesIO(raw))
        if reader.is_encrypted:
            raise CicParseError("The PDF is password-protected", "UNREADABLE_PDF")
        if len(reader.pages) > MAX_PAGES:
            raise CicParseError(f"The PDF has {len(reader.pages)} pages; a CIC report has a few", "NOT_CIC")
        # Layout mode keeps each table row on one line with its columns in
        # place; the default mode interleaves the score and rank cells.
        return "\n".join(p.extract_text(extraction_mode="layout") or "" for p in reader.pages)
    except CicParseError:
        raise
    except (PdfReadError, ValueError, KeyError, TypeError) as exc:
        raise CicParseError("The file is not a readable PDF", "UNREADABLE_PDF") from exc


def _is_signed(raw: bytes) -> bool:
    return b"/ByteRange" in raw and (b"adbe.pkcs7" in raw or b"ETSI.CAdES" in raw)


def _date(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return datetime.strptime(value, "%d/%m/%Y").date().isoformat()
    except ValueError:
        return None


def _amount(token: str) -> float:
    """A CIC amount, in million đồng. Vietnamese format: "." groups, "," is
    the decimal point (1.234,5). A lone "." followed by 3 digits is grouping."""
    if "," in token:
        return float(token.replace(".", "").replace(",", "."))
    if re.fullmatch(r"\d{1,3}(?:\.\d{3})+", token):
        return float(token.replace(".", ""))
    return float(token)


_NUMBER = re.compile(r"\d[\d.,]*")


def _value_at(lines: list[str], label: str) -> str | None:
    """The value printed for a label in section II.

    The section is a grid: each value sits BELOW its label, in the same
    column, and the lines also carry the neighbouring cells ("Điểm tín dụng:"
    shares its line with the chart's "100%"). So the value is the first token
    on the next few lines that overlaps the label's column — or, for a report
    that prints "Label: value" inline, the token right after the label.
    """
    for i, line in enumerate(lines):
        start = line.find(label)
        if start < 0:
            continue
        end = start + len(label)
        inline = re.match(r"[ \t]{0,3}(\S+)", line[end:])
        if inline:
            return inline.group(1)
        for below in lines[i + 1:i + 4]:
            for m in re.finditer(r"\S+", below):
                if m.start() < end + 2 and m.end() > start - 2:
                    return m.group()
    return None


def _columns(header: str) -> list[tuple[str, int]]:
    """Currency column centres from the "VND  USD  VND" header line."""
    return [(m.group(), (m.start() + m.end()) // 2) for m in re.finditer(r"VND|USD", header)]


def _row_values(line: str, label_end: int, columns: list[tuple[str, int]]) -> dict[str, float]:
    """The amounts on a table row, summed per currency by nearest column."""
    out: dict[str, float] = {}
    for m in _NUMBER.finditer(line, label_end):
        centre = (m.start() + m.end()) // 2
        currency = min(columns, key=lambda c: abs(c[1] - centre))[0] if columns else "VND"
        out[currency] = out.get(currency, 0.0) + _amount(m.group())
    return out


def _debt(text: str) -> dict[str, float | None]:
    lines = text.splitlines()
    header = next((l for l in lines if l.count("VND") >= 1 and "USD" in l and "Đơn vị" not in l and "Ðơn vị" not in l), "")
    columns = _columns(header)
    result: dict[str, float | None] = {
        "debt_total_vnd_million": None,
        "debt_total_usd": None,
        "debt_standard_vnd_million": None,
        "debt_attention_vnd_million": None,
        "debt_bad_vnd_million": None,
    }
    rows = {
        "Tổng cộng": ("debt_total_vnd_million", "debt_total_usd"),
        "Nợ đủ tiêu chuẩn": ("debt_standard_vnd_million", None),
        "Nợ cần chú ý": ("debt_attention_vnd_million", None),
        "Nợ xấu": ("debt_bad_vnd_million", None),
    }
    sums: dict[str, float] = {}
    for line in lines:
        stripped = line.strip()
        for label, (vnd_key, usd_key) in rows.items():
            # Group rows are "- Nợ ..." (one per lender); the grand total is
            # "Tổng cộng". The explanatory notes also start with "- Nợ ..." but
            # continue with prose, so a row must end in numbers or nothing.
            if not re.match(rf"^-?\s*{label}(\s|$)", stripped):
                continue
            rest = stripped[stripped.index(label) + len(label):]
            if rest.strip() and not re.fullmatch(r"[\d.,\s]+", rest.strip()):
                continue
            values = _row_values(line, line.index(label) + len(label), columns)
            sums[vnd_key] = sums.get(vnd_key, 0.0) + values.get("VND", 0.0)
            if usd_key:
                sums[usd_key] = sums.get(usd_key, 0.0) + values.get("USD", 0.0)
    result.update(sums)
    return result


def parse_cic_pdf(raw: bytes, *, today: date | None = None) -> CicReport:
    if not raw.startswith(b"%PDF"):
        raise CicParseError("The file is not a PDF", "NOT_A_PDF")
    return parse_cic_text(_text(raw), signed=_is_signed(raw), today=today)


def parse_cic_text(text: str, *, signed: bool, today: date | None = None) -> CicReport:
    """The report, from its layout-mode text (split out so tests can use a
    synthetic report instead of a real one full of personal data)."""
    if not text.strip():
        # A scan or a photo of the report: nothing to read without OCR.
        raise CicParseError("The PDF has no text layer (a scan?)", "UNREADABLE_PDF")
    upper = text.upper()
    if "THÔNG TIN TÍN DỤNG" not in upper or ("CIC" not in upper):
        raise CicParseError("This PDF is not a CIC credit report", "NOT_CIC")

    if "KHÁCH HÀNG VAY CÁ NHÂN" in upper:
        subject_type = "individual"
    elif "DOANH NGHIỆP" in upper or "TỔ CHỨC" in upper:
        subject_type = "business"
    else:
        raise CicParseError("The report does not say whose credit it describes", "NOT_CIC")

    warnings: list[dict[str, str]] = []

    def grab(pattern: str, flags: int = 0) -> str | None:
        m = re.search(pattern, text, flags)
        return m.group(1).strip() if m else None

    name = grab(r"Tên (?:khách hàng|doanh nghiệp):[ \t]*(\S[^\n]*)")
    report_number = grab(r"Số:[ \t]*(\S+)")
    queried_on = _date(grab(r"Ngày hỏi tin:\s*(\d{2}/\d{2}/\d{4})"))

    # Section II, read by column (see _value_at).
    lines = text.splitlines()
    score_text = _value_at(lines, "Điểm tín dụng:")
    rank_text = _value_at(lines, "Hạng:")
    scored_on = _date(_value_at(lines, "Ngày chấm điểm:"))
    # "... cao hơn điểm tín dụng của 85% tổng khách hàng ..." wraps across
    # the chart column; its tail stays on one line.
    percentile_text = grab(r"của\s+(\d{1,3})%\s+tổng")
    score = int(score_text) if score_text and re.fullmatch(r"\d{3}", score_text) else None
    rank = int(rank_text) if rank_text and re.fullmatch(r"\d{1,2}", rank_text) else None
    if score is None:
        warnings.append({"code": "NO_SCORE", "detail": "no credit score found in the report"})

    # The band table: ten "low-high" ranges, printed worst first. Rank 1 is
    # the best band.
    bands = sorted(
        ([int(a), int(b)] for a, b in re.findall(r"\b(\d{3})-(\d{3})\b", text)),
        key=lambda band: band[0],
    )
    rank_band = None
    if rank is not None and len(bands) == 10 and 1 <= rank <= 10:
        rank_band = bands[10 - rank]
        if score is not None and not (rank_band[0] <= score <= rank_band[1]):
            warnings.append({
                "code": "SCORE_RANK_MISMATCH",
                "detail": f"score {score} is outside rank {rank}'s band {rank_band[0]}-{rank_band[1]}",
            })
    if rank is not None and not 1 <= rank <= 10:
        warnings.append({"code": "SCORE_RANK_MISMATCH", "detail": f"rank {rank} is not 1-10"})
        rank = None
    rank_label = RANK_LABELS[(rank - 1) // 2] if rank else None

    debt = _debt(text)
    lenders = len(re.findall(r"^\s*\d+\.\s+(?:Ngân hàng|NH|Công ty|Quỹ|Tổ chức)", text, re.MULTILINE))

    lower = text.lower()
    if "không có lịch sử nợ xấu" in lower:
        negative_history: bool | None = False
    elif "lịch sử nợ" in lower:
        negative_history = True
        warnings.append({"code": "NEGATIVE_HISTORY", "detail": "the report lists attention or bad debt history"})
    else:
        negative_history = None
    for key, code, label in (
        ("debt_attention_vnd_million", "ATTENTION_DEBT", "needs-attention (group 2)"),
        ("debt_bad_vnd_million", "BAD_DEBT", "bad (groups 3-5)"),
    ):
        if (debt.get(key) or 0) > 0:
            warnings.append({"code": code, "detail": f"{debt[key]:g} million VND currently {label}"})

    collateral = grab(r"Bảo đảm tiền vay bằng tài sản[ \t]+(\S[^\n]*)")
    if not signed:
        warnings.append({"code": "UNSIGNED", "detail": "the PDF carries no digital signature"})
    if subject_type == "individual":
        warnings.append({
            "code": "INDIVIDUAL_REPORT",
            "detail": "an individual's report (usually the owner's), not the company's",
        })

    report = CicReport(
        subject_type=subject_type,
        subject_name=name,
        report_number=report_number,
        queried_on=queried_on,
        signed=signed,
        score=score,
        rank=rank,
        rank_band=rank_band,
        rank_label=rank_label,
        scored_on=scored_on,
        percentile=int(percentile_text) if percentile_text else None,
        lenders=lenders,
        negative_history=negative_history,
        collateral=collateral,
        warnings=warnings,
        **debt,
    )
    age = report.age_days(today or date.today())
    if age is not None and age > STALE_AFTER_DAYS:
        warnings.append({"code": "STALE_REPORT", "detail": f"scored {age} days ago; CIC rescores monthly"})
    return report

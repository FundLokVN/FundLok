"""Jobs Google Cloud Scheduler runs on prod-api (no worker is deployed).

Each is a POST that only Cloud Scheduler's service account can call (see
auth.py), safe to call twice: every job records what it sent and skips it the
next time. Kept out of the OpenAPI schema; the web app never calls them.
Spec: docs/specs/scheduled_jobs/cloud-scheduler-jobs.md.
"""

from typing import Literal

from fastapi import APIRouter, Depends, Response
from pydantic import BaseModel
from sqlalchemy.ext.asyncio import AsyncSession

from app.admin.fee_notice.service import send_pending_fee_invoice_emails
from app.core.database import get_db
from app.scheduled_jobs import acceptance, day14, money_timers, reminders, zalo_reminders
from app.scheduled_jobs.auth import require_scheduler

router = APIRouter(
    prefix="/internal/jobs",
    tags=["internal-jobs"],
    include_in_schema=False,
    dependencies=[Depends(require_scheduler)],
)


class ChannelResult(BaseModel):
    sent: int
    failed: int = 0
    # Why nothing ran (NOT_CONFIGURED, NOT_A_WORKING_DAY), when nothing did.
    skipped: str | None = None


class JobResult(BaseModel):
    job: str
    sent: int
    failed: int = 0
    # Why nothing ran (NOT_A_WORKING_DAY), when nothing did.
    skipped: str | None = None
    # repayment-reminders only: the Zalo messages the same run sent.
    zalo: ChannelResult | None = None


@router.post("/repayment-reminders", response_model=JobResult)
async def run_repayment_reminders(db: AsyncSession = Depends(get_db)):
    """Daily, 15:00 ICT: email each SME what is due today and what earlier
    days are not yet marked paid, then send it a Zalo message for each
    investor ticket due today it has not marked paid (when the template is
    configured). Nothing on a non-working day. `sent`/`failed` are the emails."""
    result = await reminders.send_repayment_reminders(db)
    zalo = await zalo_reminders.send_zalo_reminders(db)
    return JobResult(job="repayment-reminders", **result, zalo=ChannelResult(**zalo))


class Day14CutoffResult(BaseModel):
    job: str
    locked: int  # lenders newly locked by this run
    pledges: int  # late-money top-up pledges recorded by this run
    released: int = 0  # lenders unlocked: their receipt proved them in time
    failed: int = 0  # rounds that failed this run (rolled back, retried by the next run)


class Day14ReminderIn(BaseModel):
    kind: Literal["DAY14_MORNING", "DAY14_AFTERNOON"]


class Day14ReminderResult(BaseModel):
    job: str
    kind: str
    in_app: ChannelResult
    email: ChannelResult
    zalo: ChannelResult


@router.post("/day14-cutoff", response_model=Day14CutoffResult)
async def run_day14_cutoff(db: AsyncSession = Depends(get_db)):
    """Daily, 15:00 and 15:35 ICT: on rounds paying out today, lock lenders who sent nothing and those whose money
    came late, record the late money as their top-up, and tell them in the app. Idempotent per ticket
    (docs/specs/direct_transfer/day14-transfer-rule.md rule 9)."""
    result = await day14.run_day14_cutoff(db)
    return Day14CutoffResult(job="day14-cutoff", **result)


@router.post("/day14-transfer-reminders", response_model=Day14ReminderResult)
async def run_day14_transfer_reminders(body: Day14ReminderIn, db: AsyncSession = Depends(get_db)):
    """Daily, 08:00 (DAY14_MORNING) and 14:00 (DAY14_AFTERNOON) ICT: "sign and pay by 14:45" to every lender whose
    ticket on a round paying out today is unpaid, in the app, by email and on Zalo (rule 10)."""
    counts = await day14.send_day14_reminders(db, kind=body.kind)
    return Day14ReminderResult(
        job="day14-transfer-reminders", kind=body.kind,
        **{channel: ChannelResult(**value) for channel, value in counts.items()},
    )


@router.post("/fee-invoice-emails", response_model=JobResult)
async def run_fee_invoice_emails(db: AsyncSession = Depends(get_db)):
    """Daily: email any SME activation-fee invoice not emailed yet (one whose
    send after Advance failed, or a round closed some other way)."""
    sent = await send_pending_fee_invoice_emails(db)
    return JobResult(job="fee-invoice-emails", sent=sent)


class FundingAdvanceResult(BaseModel):
    job: str
    advanced: int  # commit-then-accept rounds looked at
    contracts: int  # Day-13 loan contracts generated by this run
    failed: int = 0


class AcceptanceReminderResult(BaseModel):
    job: str
    in_app: ChannelResult
    email: ChannelResult
    zalo: ChannelResult
    sms: ChannelResult


@router.post("/funding-advance", response_model=FundingAdvanceResult)
async def run_funding_advance(response: Response, db: AsyncSession = Depends(get_db)):
    """Daily, 00:00, 15:00 and 15:40 ICT: advance every commit-then-accept round with something due. At 00:00 on Day 13
    the pledge list is final and each lender's loan contract is generated; at 15:00 the silence rule decides a round
    the SME did not decide; from 15:40 on Day 14 the round closes and its pooled loan forms with everyone who paid
    (Money flow FINAL v1.0). Idempotent.

    500 when any round failed (the others are committed), so Cloud Scheduler retries in minutes instead of leaving the
    round to the next scheduled run: a 00:00 failure would otherwise keep it OPEN through the SME's whole Day 13."""
    result = await acceptance.run_funding_advance(db)
    if result["failed"]:
        response.status_code = 500
    return FundingAdvanceResult(job="funding-advance", **result)


@router.post("/acceptance-reminders", response_model=AcceptanceReminderResult)
async def run_acceptance_reminders(db: AsyncSession = Depends(get_db)):
    """Daily, 09:00 ICT: 3 days and 1 day before the 15:00 Day-13 deadline, remind the SME in the app, by email and
    on Zalo; each logged (Money flow FINAL v1.0, Day 13; D-056)."""
    counts = await acceptance.send_acceptance_reminders(db)
    return AcceptanceReminderResult(
        job="acceptance-reminders", **{channel: ChannelResult(**value) for channel, value in counts.items()}
    )


class RepaymentDayResult(BaseModel):
    job: str
    late: int  # days newly marked LATE by this run
    settled: int  # days newly settled by this run


class InvoicesResult(BaseModel):
    job: str
    overdue: int  # invoices newly marked OVERDUE
    accrued: int  # investor fee accruals created
    invoiced: int  # investor invoices issued


class CicDailyBalanceResult(BaseModel):
    job: str
    events: int  # DAILY_BALANCE events newly logged


@router.post("/repayment-day", response_model=RepaymentDayResult)
async def run_repayment_day(db: AsyncSession = Depends(get_db)):
    """Daily, 00:10 and 18:10 ICT: a day with no payment proof by 18:00 on its due date becomes LATE; a day with proof
    settles once the investor's 24 hours pass with no report. Idempotent."""
    return RepaymentDayResult(job="repayment-day", **await money_timers.run_repayment_day(db))


@router.post("/invoices", response_model=InvoicesResult)
async def run_invoices(db: AsyncSession = Depends(get_db)):
    """Daily, 00:20 ICT: mark unpaid invoices overdue, accrue investor service fees for ended months and issue the
    investors' invoices. Idempotent."""
    return InvoicesResult(job="invoices", **await money_timers.run_invoices(db))


@router.post("/cic-daily-balance", response_model=CicDailyBalanceResult)
async def run_cic_daily_balance(db: AsyncSession = Depends(get_db)):
    """Daily, 00:30 ICT: log the previous business day's outstanding balance for every active ticket in the CIC event
    log (Decree 94). Nothing the morning after a weekend or holiday. Idempotent."""
    return CicDailyBalanceResult(job="cic-daily-balance", **await money_timers.run_cic_daily_balance(db))
